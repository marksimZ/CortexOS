fn personalized_all_six_contracts_remain_available_with_custom_versions() {
    let bundle = dataset::builtin_version(2).unwrap();
    for id in [
        "zh-001",
        "math-001",
        "schema-001",
        "rag-001",
        "code-001",
        "tool-001",
    ] {
        let c = bundle
            .cases
            .iter()
            .find(|c| c.case_id == id)
            .unwrap()
            .clone();
        let candidate = cases::assigned(candidate(c)).unwrap();
        assert_eq!(
            cases::validate(&candidate, None, &[])["valid"],
            true,
            "{id}"
        );
        let mut case: dataset::Case = serde_json::from_value(candidate.case).unwrap();
        case.dataset_version = 9;
        cases::seal(&mut case).unwrap();
        assert!(dataset::validate_runtime_case(&case).is_ok());
        if case.scoring.id == "integer_equal" {
            assert_eq!(
                evaluation::evaluate(&case, "wrong", &[]).state,
                State::Failed
            );
        }
    }
}

#[test]
fn personalized_source_selection_negative_generation_and_duplicate_checks() {
    let (db, w, c) = setup();
    let dir = root();
    std::fs::write(
        dir.join("a.py"),
        "def one():\n return 1\n# do not send this line",
    )
    .unwrap();
    let snapshot = db
        .save_repository_snapshot(&w, repository::scan(&dir, false).unwrap())
        .unwrap();
    let mut options = input();
    options.repository_id = Some(snapshot.id.clone());
    let summary = db.plan_generation(&w, &c, options.clone()).unwrap();
    assert!(
        !summary["plan"]["request"]["prompt"]
            .as_str()
            .unwrap()
            .contains("do not send this line")
    );
    options.sharing = "snippets".into();
    options.snippets = vec![cases::Location {
        path: "a.py".into(),
        start: 1,
        end: 2,
    }];
    let snippets = db.plan_generation(&w, &c, options.clone()).unwrap();
    assert!(
        snippets["plan"]["request"]["prompt"]
            .as_str()
            .unwrap()
            .contains("return 1")
    );
    assert!(
        !snippets["plan"]["request"]["prompt"]
            .as_str()
            .unwrap()
            .contains("do not send this line")
    );
    options.snippets[0].end = 999;
    assert!(db.plan_generation(&w, &c, options).is_err());
    let id = summary["id"].as_str().unwrap();
    db.begin_generation(&w, id, summary["planHash"].as_str().unwrap(), &c)
        .unwrap();
    db.finish_generation(
        &w,
        id,
        Ok(CompletionOutput {
            text: "not JSON".into(),
            calls: vec![],
            usage: json!({}),
            finish_reason: "stop".into(),
            elapsed_ms: 1,
            request_hash: "a".repeat(64),
        }),
    )
    .unwrap();
    let invalid = db.generation_job(&w, id).unwrap();
    assert_eq!(invalid["status"], "invalid");
    assert_eq!(invalid["response"]["text"], "not JSON");
    assert!(
        db.publish_personalized(&w, id, json!([]), "tester")
            .is_err()
    );
    let job = db.plan_generation(&w, &c, input()).unwrap();
    let id = job["id"].as_str().unwrap();
    db.begin_generation(&w, id, job["planHash"].as_str().unwrap(), &c)
        .unwrap();
    let core = dataset::builtin_version(2).unwrap().cases[0].clone();
    let item = candidate(core);
    db.finish_generation(
        &w,
        id,
        Ok(CompletionOutput {
            text: json!({"candidates":[item,item]}).to_string(),
            calls: vec![],
            usage: json!({}),
            finish_reason: "stop".into(),
            elapsed_ms: 1,
            request_hash: "a".repeat(64),
        }),
    )
    .unwrap();
    let duplicates = db.generation_job(&w, id).unwrap();
    assert!(
        duplicates["candidates"]
            .as_array()
            .unwrap()
            .iter()
            .any(|v| v["validation"]["valid"] == false)
    );
    assert!(
        db.publish_personalized(&w, id, selection(&duplicates), "tester")
            .is_err()
    );
}

#[test]
fn personalized_batch_restart_only_allows_explicit_resume_of_unsent_items() {
    let (db, w, c) = setup();
    let job = generated(&db, &w, &c);
    let ds = db
        .publish_personalized(&w, job["id"].as_str().unwrap(), selection(&job), "tester")
        .unwrap();
    let input = batch::BatchInput {
        case_ids: vec![],
        release_models: vec![],
        repetitions: 1,
        dataset_id: ds.id,
        dataset_version: 1,
        dataset_hash: ds.content_hash,
        models: vec![batch::ModelChoice {
            kind: "cloud".into(),
            local: None,
        }],
        max_output_tokens: 512,
        price: Some(input().price),
        python_image: None,
    };
    let batch = db.plan_personalized_batch(&w, &c, input).unwrap();
    let id = batch["id"].as_str().unwrap();
    let hash = batch["planHash"].as_str().unwrap();
    assert!(
        db.begin_personalized_batch(&w, id, "incorrect", &c)
            .is_err()
    );
    db.begin_personalized_batch(&w, id, hash, &c).unwrap();
    db.set_batch_item(id, 0, "running", None, None).unwrap();
    let path = db.path.parent().unwrap().to_path_buf();
    drop(db);
    let db = Database::open(&path).unwrap();
    let reopened = db.personalized_report(&w, id).unwrap();
    assert_eq!(reopened["status"], "interrupted");
    assert_eq!(reopened["items"][0]["status"], "interrupted");
    assert_eq!(reopened["items"][1]["status"], "queued");
    assert_eq!(
        reopened["reports"][0]["statistics"]["correctness"],
        Value::Null
    );
    assert!(db.begin_personalized_batch(&w, id, hash, &c).is_ok());
    assert!(db.begin_personalized_batch(&w, id, hash, &c).is_err());
}
