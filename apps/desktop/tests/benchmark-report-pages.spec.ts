import { expect, test } from "@playwright/test";
import { createServer } from "node:http";
import { createWorkspace, launchNative, nativeInvoke } from "./native";
import type { Batch } from "../src/benchmark/personalized";

test("native report pages keep all-plan statistics and load only the opened item", async ({}, info) => {
  test.setTimeout(100_000);
  let answerRequests = 0;
  const name = "paging-fixture-no-generation", digest = "a".repeat(64);
  const server = createServer(async (req, res) => {
    res.setHeader("Content-Type", "application/json");
    if (req.url === "/api/version") return res.end(JSON.stringify({ version: "controlled-paging-fixture" }));
    if (req.url === "/api/tags") return res.end(JSON.stringify({ models: [{ name, digest, size: 1, details: { format: "gguf" } }] }));
    if (req.url === "/api/ps") return res.end(JSON.stringify({ models: [] }));
    if (req.url === "/api/chat") answerRequests++;
    res.statusCode = 400; res.end(JSON.stringify({ error: "This fixture does not generate answers" }));
  });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const address = server.address(); if (!address || typeof address === "string") throw new Error("Missing fixture listener");
  const app = await launchNative(info, { endpoint: `http://127.0.0.1:${address.port}` });
  try {
    const { page } = app; page.setDefaultTimeout(10_000); await page.emulateMedia({reducedMotion:"reduce"});
    await createWorkspace(page, "300 项分页受控验收（未运行）");
    const bootstrap = await nativeInvoke<{ workspaces: { id: string; name: string }[] }>(page, "bootstrap"), workspaceId = bootstrap.workspaces.find(w => w.name === "300 项分页受控验收（未运行）")!.id;
    const datasets = await nativeInvoke<{ id: string; version: number; contentHash: string }[]>(page, "list_benchmark_datasets", { workspaceId });
    const dataset = datasets.find(d => d.id === "cortex-core-60" && d.version === 2)!;
    const plan = await nativeInvoke<Batch>(page, "plan_standard_benchmark", { workspaceId, input: { datasetId: dataset.id, datasetVersion: 2, datasetHash: dataset.contentHash, models: [{ kind: "local", local: { model: name, expectedDigest: digest, parameters: { numCtx: 4096, numPredict: 512, temperature: 0, timeoutSeconds: 30 }, requirements: ["completion"] } }], maxOutputTokens: 512, repetitions: 5, caseIds: [], releaseModels: [] } });
    const batchId = plan.id;
    const overviewStarted = performance.now();
    const overview = await nativeInvoke<Batch>(page, "get_benchmark_overview", { workspaceId, batchId, scope: "standard" });
    const overviewReadMs = performance.now() - overviewStarted, overviewBytes = Buffer.byteLength(JSON.stringify(overview), "utf8");
    expect(overview.pagedResults).toBe(true); expect(overview.items).toBeUndefined(); expect(overview.reports![0].results).toEqual([]);
    expect(overview.reports![0].statistics.planned).toBe(300); expect(overviewBytes).toBeLessThan(100_000);
    const last = await nativeInvoke<{ total: number; rows: { ordinal: number; repetition: number }[] }>(page, "get_benchmark_result_page", { workspaceId, batchId, scope: "standard", modelIndex: 0, page: 14, pageSize: 20 });
    expect(last.total).toBe(300); expect(last.rows).toHaveLength(20); expect(last.rows[19]).toMatchObject({ ordinal: 299, repetition: 5 });
    await page.evaluate(({ workspaceId, batchId }) => { location.hash = `/benchmark?workspace=${workspaceId}&batch=${batchId}`; }, { workspaceId, batchId });
    const results = page.getByRole("region", { name: `${name} 逐题结果`, exact: true });
    await expect(results.locator(".benchmark-result")).toHaveCount(20);
    await expect(page.locator(".benchmark-result-content")).toHaveCount(0);
    const firstQuestion = await results.locator(".benchmark-result-button").first().textContent();
    await results.getByRole("button", { name: "下一页", exact: true }).click();
    await expect(results.getByText("第 2 / 15 页 · 300 项", { exact: true })).toBeVisible();
    await expect(results.locator(".benchmark-result-button").first()).toContainText("21.");
    await page.reload();await expect(results.getByText("第 2 / 15 页 · 300 项",{exact:true})).toBeVisible();
    await page.goBack();await expect(results.locator(".benchmark-result-button").first()).toHaveText(firstQuestion!);
    await page.goForward();await expect(results.locator(".benchmark-result-button").first()).toContainText("21.");
    await results.getByRole("button", { name: "上一页", exact: true }).click();
    await expect(results.locator(".benchmark-result-button").first()).toHaveText(firstQuestion!);
    await results.locator(".benchmark-result-button").first().click();
    const drawer=page.getByRole("dialog",{name:"单题详情",exact:true});
    await expect(drawer.getByText("尚未发送，没有模型输出。", { exact: true })).toBeVisible();
    const firstId=await drawer.locator(".benchmark-result-meta").textContent();
    await drawer.getByRole("button",{name:"下一题",exact:true}).click();
    await expect(drawer.locator(".benchmark-result-meta")).not.toHaveText(firstId!);
    await expect(drawer.getByRole("button",{name:"查看 3D 执行过程",exact:true})).toHaveCount(0);
    await expect(page.locator(".benchmark-result-content")).toHaveCount(1);
    await drawer.getByRole("button",{name:"关闭单题详情",exact:true}).click();
    await expect(results.locator(".benchmark-result-button").first()).toBeFocused();
    await test.step("direct item links use the real database location",async()=>{
      const located=await nativeInvoke(page,"get_benchmark_result_location",{workspaceId,batchId,scope:"standard",ordinal:299,pageSize:20});
      expect(located).toMatchObject({ordinal:299,modelIndex:0,matchesFilter:true,page:14});
      await page.evaluate(({workspaceId,batchId})=>{location.hash=`/benchmark?workspace=${workspaceId}&batch=${batchId}&item=299`;},{workspaceId,batchId});
      await expect(drawer.locator(".benchmark-result-meta")).toContainText("第 5 次");
      await expect(drawer.getByRole("button",{name:"下一题",exact:true})).toBeDisabled();
      expect(await page.evaluate(()=>new URLSearchParams(location.hash.split("?")[1]).get("page0"))).toBe("15");
      await page.reload();await expect(drawer.locator(".benchmark-result-meta")).toContainText("第 5 次");
      await page.keyboard.press("Escape");await expect(results.locator(".benchmark-result-button").last()).toBeFocused();
      await page.evaluate(({workspaceId,batchId})=>{location.hash=`/benchmark?workspace=${workspaceId}&batch=${batchId}`;},{workspaceId,batchId});
      await expect(results.locator(".benchmark-result-button").first()).toHaveText(firstQuestion!);
    });
    await test.step("database-backed filters", async()=>{
    const filters=page.getByRole("group",{name:"逐题筛选",exact:true});
    await filters.getByLabel("测试能力",{exact:true}).selectOption("integer_equal");
    await expect(results.getByText("匹配 75 / 计划 300 项",{exact:true})).toBeVisible();
    await results.getByRole("button",{name:"下一页",exact:true}).click();
    await expect(results.getByText("第 2 / 4 页 · 75 项",{exact:true})).toBeVisible();
    await results.locator(".benchmark-result-button").first().click();
    await drawer.getByRole("button",{name:"返回结果列表",exact:true}).click();
    await filters.getByLabel("重复轮次",{exact:true}).selectOption("3");
    await expect(results.getByText("第 1 / 1 页 · 15 项",{exact:true})).toBeVisible();
    await expect(page.locator(".benchmark-result-content")).toHaveCount(0);
    await expect(results.locator(".benchmark-result")).toHaveCount(15);
    for(const summary of await results.locator(".benchmark-result-button").allTextContents())expect(summary).toContain("第 3 次");
    await results.locator(".benchmark-result-button").nth(4).click();
    const itemHash=await page.evaluate(()=>location.hash);
    await page.reload();await expect(drawer.locator(".benchmark-result-meta")).toContainText("第 3 次");
    expect(await page.evaluate(()=>location.hash)).toBe(itemHash);
    await page.keyboard.press("Escape");await expect(results.locator(".benchmark-result-button").nth(4)).toBeFocused();
    await filters.getByLabel("结果状态",{exact:true}).selectOption("Passed");
    await expect(results.getByText("没有符合筛选条件的结果。",{exact:true})).toBeVisible();
    await expect(results.getByText("匹配 0 / 计划 300 项",{exact:true})).toBeVisible();
    await filters.getByRole("button",{name:"清除筛选",exact:true}).click();
    await expect(results.getByText("第 1 / 15 页 · 300 项",{exact:true})).toBeVisible();
    await page.getByLabel("排序",{exact:true}).selectOption("speed");
    await expect(page.locator(".personal-table tbody tr").first()).toContainText(name);
    });
    const after = await nativeInvoke<Batch>(page, "get_benchmark_overview", { workspaceId, batchId, scope: "standard" });
    expect(after.reports![0].statistics).toEqual(overview.reports![0].statistics);
    await page.getByRole("group",{name:"逐题筛选",exact:true}).getByLabel("测试能力",{exact:true}).selectOption("evidence_match");
    await expect(results.getByText("匹配 50 / 计划 300 项",{exact:true})).toBeVisible();
    await results.locator(".benchmark-result-button").first().click();
    await drawer.locator(".benchmark-case-sources > summary").click();
    await expect(drawer.locator(".benchmark-case-sources ol li").first()).toBeVisible();
    for (const theme of ["light", "dark"]) {
      await page.getByRole("combobox", { name: "外观", exact: true }).click();
      await page.getByRole("listbox", { name: "外观选项", exact: true }).getByRole("option", { name: theme === "dark" ? "深色" : "浅色", exact: true }).click(); await page.keyboard.press("Escape");
      for (const [width, height] of [[1366, 768], [1600, 900], [1920, 1080]]) {
        await page.setViewportSize({ width, height });
        await expect(drawer.getByText("尚未发送，没有模型输出。",{exact:true})).toBeVisible();
        const source=drawer.locator(".benchmark-case-sources");if(!await source.evaluate(e=>(e as HTMLDetailsElement).open))await source.locator("summary").first().click();
        expect((await drawer.boundingBox())!.width).toBe(720);
        await page.screenshot({path:info.outputPath(`result-drawer-top-${theme}-${width}.png`)});
        const header=drawer.locator(".panel-header"),footer=drawer.locator(".panel-footer");
        const beforeHeader=await header.boundingBox(),beforeFooter=await footer.boundingBox();
        await drawer.locator(".panel-body").evaluate(e=>e.scrollTop=e.scrollHeight);
        expect((await header.boundingBox())!.y).toBe(beforeHeader!.y);expect((await footer.boundingBox())!.y).toBe(beforeFooter!.y);
        expect((await drawer.boundingBox())!.y).toBeGreaterThanOrEqual(76);
        await page.screenshot({path:info.outputPath(`result-drawer-${theme}-${width}.png`)});
        await drawer.getByRole("button",{name:"关闭单题详情",exact:true}).click();
        await results.locator("nav").scrollIntoViewIfNeeded();
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({ path: info.outputPath(`report-page-${theme}-${width}.png`) });
        await page.getByRole("heading",{name:"全计划比较",exact:true}).scrollIntoViewIfNeeded();
        await page.screenshot({path:info.outputPath(`report-compare-${theme}-${width}.png`)});
        await results.locator(".benchmark-result-button").first().click();
        await expect(drawer).toBeVisible();
      }
    }
    expect(answerRequests).toBe(0); expect(app.consoleErrors).toEqual([]);
    await info.attach("paging-read-evidence", { body: JSON.stringify({ planned: 300, pageSize: 20, lastOrdinal: 299, overviewBytes, overviewReadMs, answerRequests, detailReadCheck: "real per-case response is fetched only inside the open drawer; header/footer stay fixed and the source fixture is read from SQLite" }, null, 2), contentType: "application/json" });
  } finally { await app.stop(); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); }
});
