  const other=await nativeInvoke<{id:string}>(page,'create_workspace',{name:'D2隔离'});
  expect(await nativeInvoke(page,'get_harness_taskset',{workspaceId:other.id,datasetId,version:1}).then(()=>false,()=>true)).toBe(true);
